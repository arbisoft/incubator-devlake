package api

import (
	"github.com/apache/incubator-devlake/core/errors"
	"github.com/apache/incubator-devlake/core/plugin"
	"github.com/google/uuid"
)

const externalIdKey = "externalId"

// PostConnections @Summary create aws connection
// @Description Create aws connection; the External ID is generated by the server
// @Tags plugins/aws
// @Param body body models.AwsConnection true "json body"
// @Success 200  {object} models.AwsConnection
// @Failure 400  {string} errcode.Error "Bad Request"
// @Failure 500  {string} errcode.Error "Internal Error"
// @Router /plugins/aws/connections [POST]
func PostConnections(input *plugin.ApiResourceInput) (*plugin.ApiResourceOutput, errors.Error) {
	if input.Body == nil {
		input.Body = map[string]interface{}{}
	}
	input.Body[externalIdKey] = uuid.NewString()
	return dsHelper.ConnApi.Post(input)
}

// PatchConnection @Summary patch aws connection
// @Description Patch aws connection; the External ID can't be changed
